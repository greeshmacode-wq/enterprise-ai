"""Ragas-based evaluation of assistant answers.

Lives in llm_service, not apps/evaluation, per the 2026-08-03 architecture
decision: this reads Conversation/Message, which llm_service owns.

Judge model is Claude Sonnet, while answers are generated by Claude Haiku
(agents.py LLM_MODEL): the judge must be at least as capable as the model
it grades, and must not be the same model - a model grading its own output
is biased towards it. The earlier local qwen2.5:7b judge was weaker than
the Haiku generator, so its scores weren't trustworthy.

Scope: only messages answered via retrieve_documents (non-empty `sources`
with resolvable chunk content) are evaluated. query_csv_dataset-answered
messages have no textual retrieved context - Faithfulness/
ContextPrecisionWithoutReference are built for text-retrieval RAG and
don't apply to tool/code-execution answers, so those are out of scope by
design, not an oversight.

No Celery: this is an on-demand analysis task, not a per-request pipeline
step, and Celery isn't running as a persistent worker in this environment
anyway - a plain async function invoked from a FastAPI route is enough.
"""

import logging

import llm_service._ragas_compat  # noqa: F401 - must precede `import ragas`
from anthropic import AsyncAnthropic # communicate with Claude asynchronously.
from asgiref.sync import sync_to_async
from ragas.llms import InstructorBaseRagasLLM, llm_factory
from ragas.metrics.collections import ContextPrecisionWithoutReference, Faithfulness
from sqlalchemy import func, select
from sqlalchemy.ext.asyncio import AsyncSession

from apps.documents.models import DocumentChunk
from llm_service.db import async_session_factory
from llm_service.models import EvaluationResult, Message, MessageRole

logger = logging.getLogger(__name__)

JUDGE_MODEL = "claude-sonnet-5"
JUDGE_TIMEOUT_SECONDS = 60.0


def _build_judge() -> InstructorBaseRagasLLM: # Ragas metrics can call to grade answers."
    client = AsyncAnthropic(timeout=JUDGE_TIMEOUT_SECONDS) # used to send non-blocking requests to the Claude API via async/await syntax.
    judge = llm_factory(JUDGE_MODEL, provider="anthropic", client=client)
    #It takes "claude-sonnet-5" + the AsyncAnthropic client and returns a ready-to-use judge object that Ragas metrics (Faithfulness, etc.) can call — so you don't have to write that wrapper yourself.
    judge.model_args.pop("temperature", None)
    judge.model_args.pop("top_p", None)
    return judge


def _resolve_context_texts_sync(chunk_ids: list[int]) -> list[str]:
    """Your assistant message stores citations/sources.[chunk_id] but ragas need actual text content"""
    content_by_id = dict(DocumentChunk.objects.filter(id__in=chunk_ids).values_list("id", "content")) # content text based on the id
    return [content_by_id[chunk_id] for chunk_id in chunk_ids if chunk_id in content_by_id] # It walks chunk_ids in order, skips any id not found in content_by_id


async def _evaluable_messages(session: AsyncSession, limit: int) -> list[Message]:
    """need to evaluavate the messages which dosent has scores"""
    already_scored = select(EvaluationResult.message_id) # message IDs that already have an evaluation result.
    print(already_scored,"already_scored")
    result = await session.execute(
        select(Message)
        .where(
            Message.role == MessageRole.ASSISTANT,
            func.jsonb_array_length(Message.sources) > 0,
            Message.id.not_in(already_scored),
        )
        .order_by(Message.id.desc())
        .limit(limit)
    )
    return list(result.scalars().all())


async def _preceding_question(session: AsyncSession, message: Message) -> str | None:
    """ need users question ->the last user question in this same conversation, sent before this particular answer."""
    result = await session.execute(
        select(Message)
        .where(
            Message.conversation_id == message.conversation_id,
            Message.role == MessageRole.USER,
            Message.id < message.id,
        )
        .order_by(Message.id.desc())
        .limit(1) # it grabs the single most recent user message before this answer.
    )
    preceding = result.scalar_one_or_none()
    return preceding.content if preceding else None


async def _score_message(message: Message, question: str | None, judge: InstructorBaseRagasLLM) -> EvaluationResult:
    """Score one message. Never raises - a scoring failure for one message
    (e.g. the judge model returning malformed structured output) becomes a
    row with `error` set, not a crashed batch.
    """
    chunk_ids = [source["chunk_id"] for source in message.sources if "chunk_id" in source]
    contexts = await sync_to_async(_resolve_context_texts_sync, thread_sensitive=False)(chunk_ids)

    if not contexts or question is None:
        return EvaluationResult(
            message_id=message.id,
            judge_model=JUDGE_MODEL,
            error="No resolvable retrieved context or no preceding question - skipped.",
        )

    try:
        faithfulness_result = await Faithfulness(llm=judge).ascore(
            user_input=question, response=message.content, retrieved_contexts=contexts
        )
        context_precision_result = await ContextPrecisionWithoutReference(llm=judge).ascore(
            user_input=question, response=message.content, retrieved_contexts=contexts
        )
    except Exception as exc:  # noqa: BLE001 - deliberately broad: any judge/parsing
        # failure for one message must become a row, not abort the whole batch.
        logger.exception("Evaluation failed for message %s", message.id)
        return EvaluationResult(message_id=message.id, judge_model=JUDGE_MODEL, error=str(exc))

    return EvaluationResult(
        message_id=message.id,
        judge_model=JUDGE_MODEL,
        faithfulness=faithfulness_result.value,
        context_precision=context_precision_result.value,
    )


async def run_evaluation(limit: int = 10) -> list[EvaluationResult]:
    """Score up to `limit` not-yet-evaluated assistant messages and persist
    the results.

    Three phases so no DB connection is held during the slow judge calls:
    read (short session) -> score (no session) -> write (short session).
    """
    judge = _build_judge()

    async with async_session_factory() as session:
        messages = await _evaluable_messages(session, limit)
        pairs = [(message, await _preceding_question(session, message)) for message in messages]

    results = [await _score_message(message, question, judge) for message, question in pairs]

    async with async_session_factory() as session:
        session.add_all(results)
        await session.commit()
        for result in results:
            await session.refresh(result)

    return results